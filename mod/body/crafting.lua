-- Crafting KNOWLEDGE and FEASIBILITY (read-only). NO emulated crafting.
-- Luis, 2026-10-25 (binding, docs/design/real-player-remediation.md): Claude must use the real player
-- code paths, so the body never consumes inputs or grants outputs itself. The emulated `craft` that
-- lived here (take inputs from the Lua store, wait, add outputs) was removed the same day; a real
-- craft will be the game's own path on a real client (InventoryController -> Server_CraftRecipe for
-- crafting stations; Server_MoveItemBetweenInventories + Server_ToggleProcessing for processing
-- stations; see DISCOVERIES "Crafting: the real player path").
--
-- What stays (route-independent):
--   * M.plan(recipe, count, station): pure; exact inputs, outputs, fuel options and the time model
--     from game data (body/recipe_data.lua, GENERATED by tools/build_recipes.py from LIVE data:
--     URecipeData, DT_CraftingStationsDataTable, DT_ProcessingStationDataTable, DT_Progression_*).
--   * M.check / M.check_recipe: would a craft be possible? Every refusal names the reason:
--     missing_input {item, have, need, missing[]}, wrong_station {need[], near[]}, not_unlocked
--     {recipe}, too_far {station, distance, max, position}. Inputs are counted with an injected
--     counter (today the Lua store; on the client route the real inventory).
--   * Station census (exact blueprint class word, ghosts skipped, the live recipe list honoured),
--     Luis's unlock mirror (ProgressComponent.RecipesUnlocked, read-only), recipe lookups.
-- Time/fuel models are UNVERIFIED (tools/craft_drift.py measures them from one real craft):
--   crafting station:   min(MaxCraftTime, CraftTime * CraftQuantityMultiplier^(count-1))
--   processing station: count * mean(MinProcessingTime, MaxProcessingTime) / ProcessingRate,
--                       fuel = FuelConsumedOverride, else ceil(seconds / FuelValue) of an accepted fuel.
--
-- Bridge handlers (probe-safe, sync, read-only):
--   craft_check {recipe | item, count, fuel?} -> ok {plan} or the precise refusal
--   recipes {item? | station?, limit=10}      -> recipe cards (inputs, outputs, stations, unlocked)
--   stations {radius=30}                      -> live station actors near the bot
-- Env: DW_CRAFT_UNLOCKS=mirror|all (all = debug), DW_CRAFT_FUEL=strict|off.
local U = require("body.util")
local jsonutil = require("jsonutil")

local M = {}

M.REACH_SLACK_CM = 100        -- capsule radius + station footprint on top of the interaction range
M.DEFAULT_RANGE_CM = 350      -- EInteractionDistance Medium (InteractableDetector.InteractionRanges)
M.REACH_DZ_CM = 300
M.SEARCH_CM = 5000            -- stations of the right type further than this count as absent
M.NEAR_LIST_CM = 3000         -- wrong_station lists other stations within this
M.MAX_COUNT = 100
M.MAX_SECONDS = 600
M.MIRROR_TTL_S = 60
M.COMPONENT_PROPS = { "CraftingStation", "ProcessingStation" }   -- BP component variable names (dump)
M.LIST_PROPS = { "ValidRecipes", "RecipesCache" }

local S = {
    data = nil, inventory = nil, mirror = nil, unlocks = "mirror", fuel = "strict",
    clock = os.time, log = nil, skills = nil, puppet = nil, bridge = nil,
}

local function log(name, d) U.event(S.log, name, d) end
local function fail(reason, d) return { ok = false, reason = reason, data = d or {} } end

-- "/Game/.../RECIPE_X.RECIPE_X" | "RECIPE_X" | "RECIPE_X@Root" -> "RECIPE_X"
local function asset(x)
    if type(x) ~= "string" then return nil end
    local a = x:match("%.([^%./]+)$") or x:match("([^/]+)$") or x
    return (a:gsub("@.*$", ""))
end
M.asset = asset

-- ------------------------------------------------------------------ configuration
function M.configure(opts)
    opts = opts or {}
    if opts.data ~= nil then S.data = opts.data end
    if opts.inventory ~= nil then S.inventory = opts.inventory end
    if opts.mirror ~= nil then S.mirror = opts.mirror end
    if opts.unlocks then S.unlocks = opts.unlocks end
    if opts.fuel then S.fuel = opts.fuel end
    if opts.clock then S.clock = opts.clock end
    if opts.log then S.log = opts.log end
    return M.status()
end

function M.data()
    if not S.data then S.data = require("body.recipe_data") end
    return S.data
end

function M.status()
    local d = S.data
    local n = 0
    if d then for _ in pairs(d.recipes or {}) do n = n + 1 end end
    return { build = d and d.build or nil, recipes = n, unlocks = S.unlocks, fuel = S.fuel,
             has_inventory = S.inventory ~= nil, has_mirror = S.mirror ~= nil }
end

function M._reset()
    S.data, S.inventory, S.mirror, S.unlocks, S.fuel = nil, nil, nil, "mirror", "strict"
    S.clock, S.log, S.skills, S.puppet, S.bridge = os.time, nil, nil, nil, nil
end

-- ------------------------------------------------------------------ names and lookups
local function item_info(path) return (M.data().items or {})[path] or {} end
local function item_id(path) return item_info(path).id or asset(path) end
local function item_name(path) return item_info(path).name end
local function station_info(sid) return (M.data().stations or {})[sid] end

local function lc(s) return type(s) == "string" and s:lower() or "" end

-- A recipe by id ("RECIPE_Process_IronBar", case-insensitive) or object path.
function M.recipe(q)
    if type(q) ~= "string" or q == "" then return nil end
    local R = M.data().recipes
    if R[q] then return q, R[q] end
    local want = lc(asset(q))
    for rid, r in pairs(R) do
        if lc(rid) == want or r.path == q then return rid, r end
    end
end

-- Recipes producing an item (path, item id or display name; exact first, then a unique substring).
function M.recipes_for_item(q)
    local R, out = M.data().recipes, {}
    if type(q) ~= "string" or q == "" then return out end
    local exact, loose = {}, {}
    local lq = lc(q)
    for rid, r in pairs(R) do
        for _, o in ipairs(r.outputs) do
            local p = o[1]
            local id, name = lc(item_id(p)), lc(item_name(p))
            if p == q or id == lq or name == lq then exact[#exact + 1] = rid; break end
            if (name ~= "" and name:find(lq, 1, true)) or id:find(lq, 1, true) then loose[#loose + 1] = rid; break end
        end
    end
    out = #exact > 0 and exact or loose
    table.sort(out)
    return out
end

-- ------------------------------------------------------------------ the pure plan
local function per_craft_processing_seconds(r, st)
    local pt = r.pt or {}
    local lo, hi = tonumber(pt[1]) or 0, tonumber(pt[2]) or tonumber(pt[1]) or 0
    local rate = tonumber(st and st.rate) or 1
    if rate <= 0 then rate = 1 end
    return ((lo + hi) / 2) / rate
end

-- What `count` crafts of recipe `rid` at a station of type `sid` consume, produce and take.
-- Pure (no inventory, no game): the emulation and the drift check both use it.
function M.plan(rid, count, sid)
    local r = M.data().recipes[rid]
    if not r then return nil, "unknown_target" end
    count = math.floor(tonumber(count) or 0)
    sid = sid or r.stations[1]
    local st = sid and station_info(sid)
    local kind = st and st.kind or "crafting"
    local p = { recipe = rid, path = r.path, crafts = count, station = sid, kind = kind, inputs = {}, outputs = {} }
    for _, c in ipairs(r.inputs) do p.inputs[#p.inputs + 1] = { path = c[1], item = item_id(c[1]), name = item_name(c[1]), count = c[2] * count } end
    for _, c in ipairs(r.outputs) do p.outputs[#p.outputs + 1] = { path = c[1], item = item_id(c[1]), name = item_name(c[1]), count = c[2] * count } end
    if kind == "processing" then
        p.seconds = per_craft_processing_seconds(r, st) * count
        p.seconds_model = "count*mean(processing_time)/rate"
        if r.fuel then
            p.fuel = { fixed = {} }
            for _, c in ipairs(r.fuel) do p.fuel.fixed[#p.fuel.fixed + 1] = { path = c[1], item = item_id(c[1]), count = c[2] * count } end
        elseif st and #(st.fuels or {}) > 0 then
            p.fuel = { burn_seconds = p.seconds, options = {} }
            for _, f in ipairs(st.fuels) do
                local fv = tonumber(item_info(f).fuel) or 0
                if fv > 0 then
                    p.fuel.options[#p.fuel.options + 1] = { path = f, item = item_id(f), fuel_value = fv,
                                                            count = math.max(1, math.ceil(p.seconds / fv)) }
                end
            end
        end
    else
        local t, tmax, qm = tonumber(r.t) or 0, tonumber(r.tmax), tonumber(r.qm) or 1
        local s = t * (qm ^ math.max(0, count - 1))
        if tmax and tmax > 0 then s = math.min(s, tmax) end
        p.seconds = s
        p.seconds_model = "min(max_craft_time, craft_time*qm^(count-1))"
    end
    if r.extra then p.extra_possible = { chance = r.extra.chance, items = r.extra.items } end
    return p
end

-- ------------------------------------------------------------------ unlocks (Luis's mirror)
local function each_set(s, fn)
    if s == nil then return false end
    return pcall(function()
        s:ForEach(function(a, b)
            local e = b ~= nil and b or a
            local v = U.try(function() return e:get() end)
            fn(v ~= nil and v or e)
        end)
    end)
end

-- Read-only: a connected player's RecipesUnlocked (TSet<URecipeData*>) and VendorReputations.
function M.read_player_unlocks(pawn)
    local pc = U.controller_of(pawn)
    local prog = pc and U.try(function() return pc.ProgressComponent end)
    if not U.valid(prog) then return nil end
    local m = { unlocked = {}, reputations = nil, source = "live", name = U.player_name(pawn) }
    local n = 0
    local ok = each_set(U.try(function() return prog.RecipesUnlocked end), function(r)
        local id = asset(U.path_of(r))
        if id then m.unlocked[id] = true; n = n + 1 end
    end)
    if not ok or n == 0 then return nil end
    local reps = {}
    local okr = pcall(function()
        prog.VendorReputations:ForEach(function(_, e)
            local v = U.try(function() return e:get() end) or e
            local tag = U.str(U.try(function() return v.ReputationTag.TagName end))
            if tag then reps[tag] = tonumber(U.try(function() return v.ReputationAmount end)) or 0 end
        end)
    end)
    if okr then m.reputations = reps end
    m.count = n
    return m
end

function M.snapshot_mirror()
    local snap = M.data().unlocked_snapshot
    if type(snap) ~= "table" or type(snap.ids) ~= "table" or #snap.ids == 0 then return nil end
    local m = { unlocked = {}, source = "catalog_snapshot", name = snap.player, count = #snap.ids }
    for _, id in ipairs(snap.ids) do m.unlocked[asset(id)] = true end
    return m
end

-- Provider for configure({mirror=...}): Luis (first connected player) live, cached MIRROR_TTL_S;
-- the catalog snapshot when nobody is online or the read fails.
function M.live_mirror()
    local cache = { at = nil, m = nil }
    return function()
        local now = S.clock()
        if cache.at and now - cache.at >= 0 and now - cache.at < M.MIRROR_TTL_S then return cache.m end
        local luis = U.find_player("luis")
        local m = (luis and M.read_player_unlocks(luis)) or M.snapshot_mirror()
        cache.at, cache.m = now, m
        return m
    end
end

local function mirror_state()
    local m = S.mirror
    if type(m) == "function" then m = U.try(m) end
    return type(m) == "table" and m or nil
end

function M.check_unlocked(rid)
    if S.unlocks == "all" then return true, { source = "all" } end
    local m = mirror_state()
    if not m or type(m.unlocked) ~= "table" then
        return false, "state_unavailable", { detail = "no mirror of Luis's recipe unlocks" }
    end
    if not m.unlocked[asset(rid)] then
        return false, "not_unlocked", { recipe = rid, unlock_source = m.source, player = m.name }
    end
    local r = M.data().recipes[rid]
    if r and r.rep and r.rep[1] then
        local have = m.reputations and m.reputations[r.rep[1]]
        if have == nil or have < (tonumber(r.rep[2]) or 0) then
            return false, "not_unlocked", { recipe = rid, detail = "vendor_reputation", tag = r.rep[1],
                                            need = r.rep[2], have = have or jsonutil.null }
        end
    end
    return true, { source = m.source }
end

-- ------------------------------------------------------------------ stations (live census)
local function live_recipe_list(a)
    for _, cp in ipairs(M.COMPONENT_PROPS) do
        local comp = U.try(function() return a[cp] end)
        if U.valid(comp) then
            for _, lp in ipairs(M.LIST_PROPS) do
                local arr = U.try(function() return comp[lp] end)
                if arr ~= nil then
                    local list, n = {}, 0
                    pcall(function()
                        arr:ForEach(function(_, e)
                            local v = U.try(function() return e:get() end) or e
                            local p = U.path_of(v)
                            if p then list[p] = true; n = n + 1 end
                        end)
                    end)
                    if n > 0 then return list, n end
                end
            end
        end
    end
end

local function reach_cm(sid)
    local st = station_info(sid) or {}
    local r = (M.data().interaction_ranges or {})[st.range or ""]
    return (tonumber(r) or M.DEFAULT_RANGE_CM) + M.REACH_SLACK_CM
end

-- Live station actors of the given types near `origin`, nearest first. Each:
-- {actor, id, station, name, kind, loc, dist, dist2d, reach_cm, live_lists_recipe}.
-- opts: {radius_cm, recipe_path (skip actors whose live list excludes it)}
function M.find_stations(sids, origin, opts)
    opts = opts or {}
    local out, seen = {}, {}
    local radius = opts.radius_cm or M.SEARCH_CM
    for _, sid in ipairs(sids) do
        local st = station_info(sid)
        for _, cls in ipairs(st and st.classes or {}) do
            for _, a in ipairs(U.find_all(cls, { skip_defaults = true })) do
                local cw = U.class_word(a)
                local id = U.short(a)
                if cw == cls and id and not seen[id] and U.try(function() return a.bIsGhosted end) ~= true then
                    local at = U.loc(a)
                    local d = origin and U.dist(origin, at) or 0
                    if at and d <= radius then
                        local list = live_recipe_list(a)
                        local listed = nil
                        if list and opts.recipe_path then listed = list[opts.recipe_path] == true end
                        if listed ~= false then
                            seen[id] = true
                            out[#out + 1] = { actor = a, id = id, station = sid, name = st.name, kind = st.kind, loc = at,
                                              dist = d, dist2d = origin and U.dist2d(origin, at) or 0,
                                              dz = origin and math.abs(origin.Z - at.Z) or 0,
                                              reach_cm = reach_cm(sid), live_list = list ~= nil }
                        end
                    end
                end
            end
        end
    end
    table.sort(out, function(x, y) return x.dist < y.dist end)
    return out
end

local function all_station_ids()
    local ids = {}
    for sid in pairs(M.data().stations or {}) do ids[#ids + 1] = sid end
    table.sort(ids)
    return ids
end

local function in_reach(s) return s.dist2d <= s.reach_cm and s.dz <= M.REACH_DZ_CM end

local function station_wire(s)
    return { station = s.station, name = s.name or jsonutil.null, id = s.id, kind = s.kind,
             position = U.to_wire(s.loc), distance = U.cm_to_m(s.dist2d), max = U.cm_to_m(s.reach_cm) }
end

local function check_station(rid, r, here)
    local found = M.find_stations(r.stations, here, { recipe_path = r.path })
    for _, s in ipairs(found) do
        if in_reach(s) then return true, s end
    end
    if found[1] then
        local d = station_wire(found[1])
        d.detail = "walk to the station first (go_to position)"
        return false, "too_far", d
    end
    local need = {}
    for _, sid in ipairs(r.stations) do
        local st = station_info(sid)
        need[#need + 1] = { station = sid, name = st and st.name or jsonutil.null }
    end
    local near = {}
    for _, s in ipairs(M.find_stations(all_station_ids(), here, { radius_cm = M.NEAR_LIST_CM })) do
        if #near >= 5 then break end
        near[#near + 1] = station_wire(s)
    end
    return false, "wrong_station", { recipe = rid, need = need, near = near,
                                     detail = #r.stations == 0 and "no station crafts this recipe" or
                                         ("no " .. tostring((need[1] or {}).name or need[1].station) .. " within " .. (M.SEARCH_CM / 100) .. " m") }
end

-- ------------------------------------------------------------------ inputs and fuel
local function check_inputs(plan)
    local inv = S.inventory
    local missing = {}
    for _, c in ipairs(plan.inputs) do
        local have = tonumber(inv.count(c.path)) or 0
        if have < c.count then missing[#missing + 1] = { item = c.item, name = c.name or jsonutil.null, have = have, need = c.count } end
    end
    return missing
end

-- Choose the fuel: the requested one, else the first accepted fuel the bot holds enough of after the
-- inputs are set aside. Returns {path, item, count} or nil, missing-entry.
local function choose_fuel(plan, want)
    local f = plan.fuel
    if not f or S.fuel == "off" then return nil end
    if f.fixed then return { fixed = f.fixed } end
    local reserved = {}
    for _, c in ipairs(plan.inputs) do reserved[c.path] = (reserved[c.path] or 0) + c.count end
    local first
    for _, o in ipairs(f.options) do
        if not want or o.path == want or lc(o.item) == lc(want) or lc(item_name(o.path)) == lc(want) then
            local have = (tonumber(S.inventory.count(o.path)) or 0) - (reserved[o.path] or 0)
            first = first or { item = o.item, name = item_name(o.path) or jsonutil.null, have = math.max(0, have), need = o.count, fuel = true }
            if have >= o.count then return { path = o.path, item = o.item, count = o.count } end
        end
    end
    if not first then
        return nil, { item = want or "fuel", have = 0, need = 1, fuel = true, detail = "no accepted fuel" }
    end
    return nil, first
end

-- ------------------------------------------------------------------ the full check
local function resolve(args)
    if args.recipe ~= nil then
        if type(args.recipe) ~= "string" or args.recipe == "" then return nil, fail("invalid_args", { detail = "recipe must be a string" }) end
        local rid = M.recipe(args.recipe)
        if not rid then return nil, fail("unknown_target", { recipe = args.recipe, detail = "no such recipe" }) end
        return { rid }
    end
    if type(args.item) ~= "string" or args.item == "" then
        return nil, fail("invalid_args", { detail = "recipe or item is required" })
    end
    local list = M.recipes_for_item(args.item)
    if #list == 0 then return nil, fail("unknown_target", { item = args.item, detail = "no recipe makes this item" }) end
    return list
end

-- Crafts needed: `count` crafts for a recipe; for an item, enough crafts for `count` items.
local function crafts_for(rid, args, by_item)
    local n = math.floor(tonumber(args.count) or 1)
    if not by_item then return n end
    local r = M.data().recipes[rid]
    local per = 1
    for _, o in ipairs(r.outputs) do
        local id, name = lc(item_id(o[1])), lc(item_name(o[1]))
        if o[1] == args.item or id == lc(args.item) or name == lc(args.item) or name:find(lc(args.item), 1, true) or id:find(lc(args.item), 1, true) then
            per = o[2]; break
        end
    end
    return math.ceil(n / math.max(1, per))
end

-- One recipe, all checks in order: unlocked -> inputs (+fuel) -> station. Returns
-- true, plan, station  or  false, reason, data (with `checks` naming every check's verdict).
function M.check_recipe(rid, crafts, here, opts)
    opts = opts or {}
    local r = M.data().recipes[rid]
    local checks = {}
    local ok_u, why_u, d_u = M.check_unlocked(rid)
    checks.unlocked = ok_u
    local ok_s, station, d_s = check_station(rid, r, here)
    checks.station = ok_s and true or station
    local plan = M.plan(rid, crafts, ok_s and station.station or nil)
    local missing = check_inputs(plan)
    local fuel, fuel_missing = nil, nil
    if plan.kind == "processing" then fuel, fuel_missing = choose_fuel(plan, opts.fuel) end
    if fuel_missing then missing[#missing + 1] = fuel_missing end
    if fuel and fuel.fixed then
        for _, c in ipairs(fuel.fixed) do
            local have = tonumber(S.inventory.count(c.path)) or 0
            if have < c.count then missing[#missing + 1] = { item = c.item, have = have, need = c.count, fuel = true } end
        end
    end
    checks.inputs = #missing == 0
    if not ok_u then
        local d = d_u or {}
        d.checks = checks
        return false, why_u, d
    end
    if #missing > 0 then
        local m1 = missing[1]
        return false, "missing_input", { recipe = rid, item = m1.item, have = m1.have, need = m1.need, missing = missing,
                                         crafts = crafts, checks = checks }
    end
    if not ok_s then
        d_s = d_s or {}
        d_s.recipe, d_s.checks = rid, checks
        return false, station, d_s
    end
    plan.fuel_used = fuel
    return true, plan, station
end

-- Pick among candidate recipes: the first that passes; else the "closest" refusal (most checks
-- passed), with the others listed as alternatives.
local RANK = { not_unlocked = 0, state_unavailable = 0, missing_input = 1, wrong_station = 2, too_far = 3 }

function M.check(args, here)
    local cands, bad = resolve(args)
    if not cands then return false, bad.reason, bad.data end
    local count = tonumber(args.count)
    if count == nil then count = 1 end
    if count ~= math.floor(count) or count < 1 or count > M.MAX_COUNT then
        return false, "invalid_args", { detail = "count must be an integer 1.." .. M.MAX_COUNT }
    end
    local by_item = args.recipe == nil
    local best, alts = nil, {}
    for _, rid in ipairs(cands) do
        local crafts = crafts_for(rid, args, by_item)
        local ok, a, b = M.check_recipe(rid, crafts, here, { fuel = args.fuel })
        if ok then
            if a.seconds > M.MAX_SECONDS then
                return false, "invalid_args", { detail = "would take " .. math.floor(a.seconds) .. " s (max " .. M.MAX_SECONDS .. ")", recipe = rid }
            end
            return true, a, b
        end
        local entry = { recipe = rid, reason = a, data = b, rank = RANK[a] or -1 }
        alts[#alts + 1] = entry
        if not best or entry.rank > best.rank then best = entry end
    end
    local data = best.data or {}
    if #alts > 1 then
        data.alternatives = {}
        for _, e in ipairs(alts) do
            if e ~= best then data.alternatives[#data.alternatives + 1] = { recipe = e.recipe, reason = e.reason } end
        end
    end
    return false, best.reason, data
end

local function summary_of(list)
    local out = {}
    for _, c in ipairs(list) do out[#out + 1] = { item = c.item or item_id(c.path), count = c.count } end
    return out
end

-- ------------------------------------------------------------------ handlers
local function puppet_here()
    local p, err = S.puppet.ensure_ready()
    if not p then return nil, fail("companion_down", { detail = err }) end
    local here = U.loc(p)
    if not here then return nil, fail("companion_down", { detail = "no position" }) end
    return p, here
end

local function plan_wire(plan, station)
    return { recipe = plan.recipe, crafts = plan.crafts, kind = plan.kind, inputs = summary_of(plan.inputs),
             outputs = summary_of(plan.outputs), seconds = U.round(plan.seconds, 2), seconds_model = plan.seconds_model,
             fuel = plan.fuel_used and (plan.fuel_used.fixed and summary_of(plan.fuel_used.fixed)
                 or { { item = plan.fuel_used.item, count = plan.fuel_used.count } }) or jsonutil.null,
             station = station and station_wire(station) or jsonutil.null }
end

local function h_craft_check(args)
    if not S.inventory then return fail("state_unavailable", { detail = "bot inventory store not initialised" }) end
    if args.recipe == nil and args.item == nil then return fail("invalid_args", { detail = "recipe or item is required" }) end
    local p, here = puppet_here()
    if not p then return here end
    local ok, plan, station = M.check(args, here)
    if not ok then return fail(plan, station) end
    return { ok = true, data = { plan = plan_wire(plan, station) } }
end

local function card(rid)
    local r = M.data().recipes[rid]
    local st = {}
    for _, sid in ipairs(r.stations) do st[#st + 1] = (station_info(sid) or {}).name or sid end
    local function lst(l) local o = {} for _, c in ipairs(l) do o[#o + 1] = { item = item_id(c[1]), name = item_name(c[1]) or jsonutil.null, count = c[2] } end return o end
    local unlocked = M.check_unlocked(rid)
    return { recipe = rid, inputs = lst(r.inputs), outputs = lst(r.outputs), stations = st, unlocked = unlocked == true }
end

local function h_recipes(args)
    local limit = math.max(1, math.min(50, math.floor(tonumber(args.limit) or 10)))
    local list = {}
    if type(args.item) == "string" and args.item ~= "" then
        list = M.recipes_for_item(args.item)
    elseif type(args.station) == "string" and args.station ~= "" then
        local want = lc(args.station)
        for rid, r in pairs(M.data().recipes) do
            for _, sid in ipairs(r.stations) do
                if lc(sid) == want or lc((station_info(sid) or {}).name) == want then list[#list + 1] = rid; break end
            end
        end
        table.sort(list)
    else
        return fail("invalid_args", { detail = "item or station is required" })
    end
    local out = {}
    for i = 1, math.min(#list, limit) do out[i] = card(list[i]) end
    return { ok = true, data = { recipes = out, total = #list } }
end

local function h_stations(args)
    local radius = tonumber(args.radius) or 30
    if radius <= 0 or radius > 200 then return fail("invalid_args", { detail = "radius must be 0..200 m" }) end
    local p = S.puppet.get()
    local origin = (p and U.loc(p)) or (U.split_pawns()[1] and U.loc(U.split_pawns()[1]))
    if not origin then return fail("companion_down", { detail = "no position to search from" }) end
    local out = {}
    for _, s in ipairs(M.find_stations(all_station_ids(), origin, { radius_cm = radius * 100 })) do
        local w = station_wire(s)
        w.in_reach = in_reach(s)
        out[#out + 1] = w
    end
    return { ok = true, data = { stations = out } }
end

-- No `craft` handler on purpose (Luis, 2026-10-25, docs/design/real-player-remediation.md): the body
-- never consumes inputs or grants outputs itself. The protocol tool `craft` answers not_implemented
-- (bridge.lua KNOWN) until the real-client route calls the game's own crafting path.
M.HANDLERS = { craft_check = h_craft_check, recipes = h_recipes, stations = h_stations }

-- opts: {skills, puppet, inventory (counter with .count(path)), data, mirror (false = none), unlocks, fuel}
function M.register(bridge, log_mod, opts)
    opts = opts or {}
    S.bridge, S.log = bridge, log_mod
    S.skills = opts.skills or require("body.skills")
    S.puppet = opts.puppet or require("body.puppet")
    if opts.inventory ~= nil then S.inventory = opts.inventory end
    if opts.data then S.data = opts.data end
    S.unlocks = opts.unlocks or os.getenv("DW_CRAFT_UNLOCKS") or S.unlocks
    S.fuel = opts.fuel or os.getenv("DW_CRAFT_FUEL") or S.fuel
    if opts.mirror ~= false and S.mirror == nil then S.mirror = opts.mirror or M.live_mirror() end
    M.data()
    for name, fn in pairs(M.HANDLERS) do bridge.handlers[name] = S.skills._probe_guard(name, fn) end
    log("crafting_registered", M.status())
    return M
end

return M
