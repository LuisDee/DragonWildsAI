"""Creature facts from the wiki snapshot (data/wiki/pages, CC BY-NC-SA, see data/wiki/manifest.json) ->
client_mod/scripts/creature_wiki.lua (DATA, generated: do not edit by hand).

Per monster infobox: power level(s), health, race, weakness / resistance / immune. Damage-type words become
the game's damage-type tags (from client_mod/scripts/weapons_data.lua, e.g. "Water" -> DamageType.Magical.Water);
status words (Poison, Burning, Bleed, ...) are kept as immune_effects. combat.known_affinities reads it with the
source label "wiki" (below learned, above priors). Usage: .venv\\Scripts\\python.exe -m tools.gen_creature_wiki
"""
from __future__ import annotations

import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PAGES = REPO / "data/wiki/pages"
WEAPONS = REPO / "client_mod/scripts/weapons_data.lua"
OUT = REPO / "client_mod/scripts/creature_wiki.lua"

KEYS = ["name", "name1", "name2", "name3", "location", "location1", "location2", "location3", "power level", "power level1",
        "power level2", "power level3", "health", "health1", "health2", "health3", "race", "weakness", "resistance", "immune",
        "aggressive", "respawn", "experience", "experience1", "experience2", "experience3", "examine", "attack style", "gender",
        "status"]
KEY_RX = re.compile(r"(?<![\w-])(" + "|".join(re.escape(k) for k in sorted(KEYS, key=len, reverse=True)) + r"):\s", re.I)


def damage_tags() -> dict[str, str]:
    tags = set(re.findall(r'"(DamageType\.[A-Za-z.]+)"', WEAPONS.read_text(encoding="utf-8")))
    tags |= {"DamageType.Magical.Fire", "DamageType.Magical.Water", "DamageType.Magical.Air", "DamageType.Magical.Earth",
             "DamageType.Ranged"}
    return {t.rsplit(".", 1)[-1].lower(): t for t in tags}


def infobox(text: str) -> dict[str, str]:
    head = text[:2500]
    parts = KEY_RX.split(head)
    out: dict[str, str] = {}
    for i in range(1, len(parts) - 1, 2):
        k, v = parts[i].lower(), parts[i + 1].strip()
        out.setdefault(k, v)
    return out


def words(v: str | None) -> list[str]:
    if not v:
        return []
    v = re.split(r"\s{2,}|(?<=[a-z])\s(?=[A-Z][a-z]+ [a-z])", v)[0]  # stop at the prose that follows the box
    out = []
    for w in re.split(r"[,/]| and ", v):
        w = w.strip(" .*-")
        if w and w.lower() not in ("none", "n/a", "-") and len(w) < 20:
            out.append(w)
    return out


def num(v: str | None) -> int | None:
    m = re.match(r"\s*([\d,]+)", v or "")
    return int(m.group(1).replace(",", "")) if m else None


def build() -> dict[str, dict]:
    dmg = damage_tags()
    out: dict[str, dict] = {}
    for f in sorted(PAGES.glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        text = " ".join((s.get("text") or "") for s in d.get("sections") or [] if isinstance(s, dict))
        if "power level" not in text[:2500] or "weakness:" not in text[:2500]:
            continue
        box = infobox(text)
        # a Multi Infobox (NPC + Monster): the monster part starts at the last "name:" before "power level:"
        i = text.find("power level")
        j = text.rfind("name: ", 0, i)
        if j > 0:
            box = {**box, **infobox(text[j:])}
        name = re.sub(r"\s+", " ", (box.get("name") or box.get("name1") or d.get("title") or ""))
        name = re.split(r"\s(?:location|power level|health|race|weakness)\d?:", name, flags=re.I)[0].strip()
        if not name:
            continue
        rec: dict = {"title": d.get("title"), "url": d.get("url")}
        pls = [num(box.get(k)) for k in ("power level", "power level1", "power level2", "power level3") if num(box.get(k)) is not None]
        hps = [num(box.get(k)) for k in ("health", "health1", "health2", "health3") if num(box.get(k)) is not None]
        if pls:
            rec["pl"] = pls
        if hps:
            rec["hp"] = hps
        if box.get("race"):
            rec["race"] = words(box["race"])[:1]
        for key, field in (("weakness", "weak"), ("resistance", "resist"), ("immune", "immune")):
            for w in words(box.get(key)):
                tag = dmg.get(w.lower())
                if tag:
                    rec.setdefault(field, []).append(tag)
                elif key == "immune":
                    rec.setdefault("immune_effects", []).append(w)
        out[name.lower()] = rec
    return out


def lua(v, ind=""):
    if isinstance(v, dict):
        inner = ", ".join(f'[{json.dumps(k)}] = {lua(x)}' for k, x in sorted(v.items()))
        return "{ " + inner + " }"
    if isinstance(v, list):
        return "{ " + ", ".join(lua(x) for x in v) + " }"
    if isinstance(v, (int, float)):
        return str(v)
    return json.dumps(str(v))


def main():
    data = build()
    lines = ["-- DATA (generated by tools/gen_creature_wiki.py from the wiki snapshot data/wiki/pages; do not edit).",
             "-- Monster infobox facts per lower-case name: pl, hp (lists: variants), race, weak/resist/immune (damage-type",
             "-- tags), immune_effects (status words). Source label in combat.known_affinities: \"wiki\".",
             "return {"]
    for k, v in sorted(data.items()):
        lines.append(f'    [{json.dumps(k)}] = {lua(v)},')
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(data)} creatures -> {OUT}")


if __name__ == "__main__":
    main()
