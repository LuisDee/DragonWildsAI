"""Consumable effects from the wiki snapshot (data/wiki/pages; CC BY-NC-SA) -> client_mod/scripts/consumable_wiki.lua
(DATA, generated: do not edit by hand).

Per food / potion / drink infobox: item type, health, duration, perks, and what the perks do to tracked statuses:
cures (the perk text says NEGATES / removes X) and resists (RESISTANCE to X, with a % from the description when
given). Status words are the game's ETrackedStatusEffect names (Poison, Burning, Bleeding, Cold, Wither, Slow).
combat.lua uses it to pick a cure while poisoned (labelled source "wiki").
Usage: .venv\\Scripts\\python.exe -m tools.gen_consumable_wiki
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from tools.gen_creature_wiki import lua

REPO = Path(__file__).resolve().parents[1]
PAGES = REPO / "data/wiki/pages"
OUT = REPO / "client_mod/scripts/consumable_wiki.lua"
STATUS = {"poison": "Poison", "burning": "Burning", "burn": "Burning", "bleed": "Bleeding", "bleeding": "Bleeding",
          "cold": "Cold", "wither": "Wither", "slow": "Slow"}
TYPES = ("food", "potion", "drink", "consumable", "infusion")


KEYS = ["name", "item type", "duration", "weight", "stacklimit", "description", "sustenance", "health", "hydration",
        "perk", "perk1", "perk2", "perk3", "perkDesc", "perkDesc1", "perkDesc2", "perkDesc3", "Recipe", "power level",
        "examine", "value"]
KEY_ALT = "|".join(re.escape(k) for k in sorted(KEYS, key=len, reverse=True))


def field(text: str, key: str) -> str | None:
    m = re.search(r"(?<![\w-])" + re.escape(key) + r":\s*(.+?)(?=\s+(?:" + KEY_ALT + r"):\s|$)", text[:3000])
    return m.group(1).strip() if m else None


def effects(text: str) -> tuple[set, dict]:
    """cures / resists from the page's own words (infobox perk text + the first paragraph)."""
    low = text[:2500].lower()
    cures, resists = set(), {}
    for w, st in STATUS.items():
        if not re.search(r"\b" + w + r"\b", low):
            continue
        if re.search(r"(removes|negates|cures)[^.]{0,40}\b" + w, low) or re.search(r"negates and grants resist[a-z]* to " + w, low):
            cures.add(st)
        m = (re.search(r"(\d+)% resistance (?:from|to) (?:future )?" + w, low)
             or re.search(r"reduces " + w + r" buildup by (\d+)%", low))
        if m:
            resists[st] = int(m.group(1))
        elif re.search(r"resist[a-z]* (?:to|from) " + w, low):
            resists.setdefault(st, 0)
    return cures, resists


def build() -> dict[str, dict]:
    out: dict[str, dict] = {}
    for f in sorted(PAGES.glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        text = re.sub(r"\s+", " ", " ".join((s.get("text") or "") for s in d.get("sections") or [] if isinstance(s, dict)))
        itype = (field(text, "item type") or "").lower()
        if not any(t in itype for t in TYPES):
            continue
        name = (field(text, "name") or d.get("title") or "").strip()
        rec: dict = {"type": itype.split()[0], "title": d.get("title"), "url": d.get("url")}
        hp = re.match(r"(\d+)", field(text, "health") or "")
        if hp:
            rec["heal"] = int(hp.group(1))
        dur = re.match(r"(\d+)", field(text, "duration") or "")
        if dur:
            rec["duration_s"] = int(dur.group(1))
        soul = re.search(r"(\d+)\s*soulscourge", text[:2500], re.I)  # "provides 10 hydration but also 20 Soulscourge"
        rec["soulscourge"] = int(soul.group(1)) if soul else 0  # 0 = the page names none (stay-fed reflex: clean first)
        perks = [p for p in (field(text, k) for k in ("perk", "perk1", "perk2", "perk3")) if p]
        cures, resists = effects(text)
        if perks:
            rec["perks"] = perks
        if cures:
            rec["cures"] = sorted(cures)
        if resists:
            rec["resists"] = {k: v for k, v in sorted(resists.items())}
        out[name.lower()] = rec
    return out


def main():
    data = build()
    lines = ["-- DATA (generated by tools/gen_consumable_wiki.py from the wiki snapshot data/wiki/pages; do not edit).",
             "-- Per lower-case display name: type, heal, duration_s, soulscourge (0 = none named), perks, cures {status}, resists {status = %}.",
             "return {"]
    for k, v in sorted(data.items()):
        lines.append(f"    [{json.dumps(k)}] = {lua(v)},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    n = sum(1 for v in data.values() if v.get("cures") or v.get("resists"))
    print(f"{len(data)} consumables ({n} cure/resist a status) -> {OUT}")


if __name__ == "__main__":
    main()
