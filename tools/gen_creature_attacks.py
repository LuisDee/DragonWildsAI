"""The game's own attack damage per creature (DT_AIAttackDamage rows, matched in data/bestiary.json game_attacks) ->
client_mod/scripts/creature_attacks.lua (DATA, generated: do not edit by hand).

combat.enemy_dps reads it when he has no fights of his own with a creature: intake per attacker = mean attack
damage x cfg.odds_landed_per_s (measured on his fights of 16-18 Nov 2026; tools/fight_odds_truth.py).
Usage: .venv\\Scripts\\python.exe -m tools.gen_creature_attacks
"""
from __future__ import annotations

import json
from pathlib import Path

from tools.gen_creature_wiki import lua

REPO = Path(__file__).resolve().parents[1]
BESTIARY = REPO / "data/bestiary.json"
OUT = REPO / "client_mod/scripts/creature_attacks.lua"


def build(bestiary: dict | None = None) -> dict[str, dict]:
    """{lower-case name: {mean, max, n}} for every creature whose game attack rows carry a damage."""
    b = bestiary if bestiary is not None else json.loads(BESTIARY.read_text(encoding="utf-8"))
    out = {}
    for name, c in (b.get("creatures") or {}).items():
        dmg = [float(x) for a in (c.get("game_attacks") or []) if isinstance(a, dict)
               for x in (a.get("damage") or []) if isinstance(x, (int, float)) and x > 0]
        if dmg:
            out[str(name).lower()] = {"mean": round(sum(dmg) / len(dmg), 2), "max": max(dmg), "n": len(dmg)}
    return out


def main():
    data = build()
    lines = ["-- DATA (generated by tools/gen_creature_attacks.py from data/bestiary.json game_attacks; do not edit).",
             "-- The game's attack damage rows per lower-case creature name: mean and max damage per hit, n rows.",
             "-- combat.enemy_dps: intake per attacker = mean x cfg.odds_landed_per_s when he has no fights of his own.",
             "return {"]
    for k, v in sorted(data.items()):
        lines.append(f'    [{json.dumps(k)}] = {lua(v)},')
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(data)} creatures -> {OUT}")


if __name__ == "__main__":
    main()
